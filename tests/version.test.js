'use strict';
// One version number, three places (package.json, `ak --version` of both targets) and a changelog section for it.
const fs = require('fs'), path = require('path'), cp = require('child_process');
const root = path.join(__dirname, '..');
let bad = 0, n = 0;
const t = (name, ok, info) => { n++; if (!ok) { bad++; console.log('FAIL', name, info === undefined ? '' : '\n   ' + JSON.stringify(info)); } };
const v = require('../package.json').version;
t('package.json has a version like X.Y.Z', /^\d+\.\d+\.\d+$/.test(v), v);
const nat = cp.spawnSync(path.join(root, 'bin', 'ak'), ['--version'], { encoding: 'utf8' });
t('bin/ak --version matches package.json', nat.stdout === `ak ${v}\n`, nat.stdout);
const js = cp.spawnSync('node', [path.join(root, 'boot', 'ak.js'), '--version'], { encoding: 'utf8' });
t('boot/ak.js --version matches package.json', js.stdout === `ak ${v}\n`, js.stdout);
const src = fs.readFileSync(path.join(root, 'src', 'main.aklang'), 'utf8');
t('src/main.aklang VERSION matches package.json', src.includes(`VERSION="${v}"`));
const log = fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8');
t('CHANGELOG.md has a section for the current version', new RegExp(`^## ${v.replace(/\./g, '\\.')} \\(\\d{4}-\\d{2}-\\d{2}\\)$`, 'm').test(log));
t('CHANGELOG.md has an Unreleased section on top', /^## Unreleased$/m.test(log) && log.indexOf('## Unreleased') < log.indexOf(`## ${v}`));
const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
t('README links the stability policy', readme.includes('docs/stability.md'));
console.log(bad ? bad + ' of ' + n + ' version checks failed' : n + ' version checks passed');
process.exit(bad ? 1 : 0);
